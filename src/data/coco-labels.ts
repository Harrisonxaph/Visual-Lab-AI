export function catalogFor(model: DetectorConfiguration) {
  return model.sha256 === COCO_CATALOG.modelSha256 &&
    model.labelSet === "COCO" &&
    model.categories === 80
    ? COCO_CATALOG
    : null;
}
export function searchCategories(
  model: DetectorConfiguration,
  query: string,
): readonly string[] {
  return (
    catalogFor(model)?.labels.filter((label) =>
      label.includes(query.trim().toLowerCase()),
    ) ?? []
  );
}
